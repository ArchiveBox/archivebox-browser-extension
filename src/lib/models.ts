const batchSize = 500;

// Generated by `pnpm db:generate` from schema.ts (plus hand-written ones for
// what Drizzle cannot express), applied in file-name order. PRAGMA
// user_version counts how many have run.
const migrations = Object.entries(import.meta.glob<string>('../../drizzle/*.sql', { query: '?raw', import: 'default', eager: true }))
  .sort(([a], [b]) => a.localeCompare(b)).map(([, script]) => script);

let ready: Promise<Database<typeof schema>> | undefined;

// Opens the database, applies migrations, and moves pre-3.4 data out of
// chrome.storage.local, once per context. Every export awaits this.
function db(): Promise<Database<typeof schema>> {
  ready ??= (async () => {
    await migratePublishedStorage();
    const connection = await database(schema);
    await connection.migrate(migrations);
    await importLegacyEntries(connection);
    return connection;
  })().catch((error) => {
    ready = undefined;
    throw error;
  });
  return ready;
}

// storage_schema_version 1 kept every snapshot in one chrome.storage.local
// `entries` array. Version 2 moves them into SQLite, once, in batches. Each
// batch is an idempotent upsert keyed by id, so a worker stopped midway just
// redoes it on the next start; the version flips only after every id is
// confirmed in the database. The array is kept, unread, as entries_backup_v1
// for one release so a downgrade can be recovered.
async function importLegacyEntries(connection: Database<typeof schema>): Promise<void> {
  // getConfig also enters the storage migration lock. Web Locks are not
  // reentrant: read configuration before acquiring it or first-run UI freezes.
  const config = await getConfig();
  await navigator.locks.request('archivebox-storage-migration', async () => {
    const { storage_schema_version } = await browser.storage.local.get('storage_schema_version');
    if (storage_schema_version === 2) return;
    if (storage_schema_version !== 1) throw new Error('Unsupported extension storage version.');
    const { entries } = await browser.storage.local.get('entries');
    const unique = new Map<string, Snapshot>();
    for (const entry of Array.isArray(entries) ? entries as Snapshot[] : []) {
      if (entry && typeof entry.id === 'string' && typeof entry.url === 'string') unique.set(entry.id, entry);
    }
    const snapshots = [...unique.values()];
    for (let start = 0; start < snapshots.length; start += batchSize) {
      const batch = snapshots.slice(start, start + batchSize);
      await connection.transaction(async (tx) => {
        for (const snapshot of batch) await writeSnapshot(tx, snapshot, config);
      });
      const ids = batch.map(snapshot => snapshot.id);
      const [saved] = await connection.orm.select({ count: count() }).from(core_snapshot).where(inArray(core_snapshot.id, ids));
      if (saved?.count !== ids.length) throw new Error('Saved snapshots could not be moved to the new database.');
    }
    // Older versions also left copies in storage.sync. Nothing reads them;
    // keep them with the backup instead of in the user's sync quota.
    const { entries: syncEntries } = await browser.storage.sync.get('entries').catch(() => ({ entries: undefined }));
    await browser.storage.local.set({ storage_schema_version: 2,
      entries_backup_v1: { entries: entries ?? [], ...(syncEntries ? { sync_entries: syncEntries } : {}) } });
    await browser.storage.local.remove('entries');
    if (syncEntries) await browser.storage.sync.remove('entries');
  });
}

// --- Retention schedule (the server's ModelWithDeleteAfter.delete_at) ---------
// A snapshot row, or one of its captures, may be deleted locally once every
// server it was sent to has confirmed it and the configured retention period
// has passed since. These compute that moment (null: never, or not yet
// confirmed); retention.ts deletes what is due, after re-confirming with the
// server.

function captureRetention(kind: CaptureKind, config: ConfigState): number | null {
  if (!config.save_snapshots_locally) return 0;
  let ttl = config.capture_retention_ms[kind] ?? config.local_retention_ms;
  // A capture never outlives its snapshot.
  if (config.local_retention_ms !== 'never' && (ttl === 'never' || ttl > config.local_retention_ms)) ttl = config.local_retention_ms;
  return ttl === 'never' ? null : ttl;
}

function snapshotServers(snapshot: Snapshot, config: ConfigState): ServerConfiguration[] | null {
  const ids = Object.keys(snapshot.remote_copies || {});
  const servers = ids.map(id => config.servers.find(server => server.id === id));
  return ids.length && servers.every(Boolean) && !snapshot.unassigned_remote_copy ? servers as ServerConfiguration[] : null;
}

function latest(times: Array<string | undefined>): number {
  return Math.max(...times.map(time => Date.parse(time || '')).filter(Number.isFinite));
}

export function snapshotDeleteAt(snapshot: Snapshot, config: ConfigState): string | null {
  const ttl = config.save_snapshots_locally ? config.local_retention_ms : 0;
  const servers = snapshotServers(snapshot, config);
  if (ttl === 'never' || !servers) return null;
  let confirmed = -Infinity;
  for (const server of servers) {
    const copy = snapshot.remote_copies![server.id]!;
    const submitted = latest([copy.submitted_at, ...Object.values(copy.artifacts || {}).map(receipt => receipt?.uploaded_at)]);
    if (copy.status !== 'complete' || !Number.isFinite(submitted)
      || copy.submitted_to !== new URL(server.server).toString().replace(/\/$/, '')) return null;
    confirmed = Math.max(confirmed, submitted);
  }
  return new Date(confirmed + ttl).toISOString();
}

export function archiveResultDeleteAt(snapshot: Snapshot, kind: CaptureKind, config: ConfigState): string | null {
  const capture = snapshot[kind];
  const ttl = captureRetention(kind, config);
  const servers = snapshotServers(snapshot, config);
  if (!capture || ttl === null || !servers) return null;
  let confirmed = -Infinity;
  for (const server of servers) {
    const copy = snapshot.remote_copies![server.id]!;
    const receipt = copy.artifacts?.[kind];
    const uploaded = Date.parse(receipt?.uploaded_at || '');
    if (copy.submitted_to !== server.server || receipt?.status !== 'uploaded' || receipt.path !== capture.path
      || receipt.captured_at !== capture.capturedAt || !Number.isFinite(uploaded)) return null;
    confirmed = Math.max(confirmed, uploaded);
  }
  return new Date(confirmed + ttl).toISOString();
}

// --- Row mapping ----------------------------------------------------------------

async function writeSnapshot(tx: Tx, snapshot: Snapshot, config: ConfigState): Promise<void> {
  const now = new Date().toISOString();
  const { id, url, title = '', tags = [] } = snapshot;
  const fields = {
    modified_at: now,
    created_by_username: snapshot.created_by_username || 'system',
    url,
    bookmarked_at: snapshot.timestamp,
    title,
    depth: snapshot.depth ?? 0,
    delete_at: snapshotDeleteAt(snapshot, config),
    favIconUrl: snapshot.favIconUrl ?? null,
    persona_overrides: snapshot.persona_overrides ?? null,
    unassigned_remote_copy: snapshot.unassigned_remote_copy ?? null,
  };
  await tx.insert(core_snapshot).values({ id, created_at: now, ...fields }).onConflictDoUpdate({ target: core_snapshot.id, set: fields });
  await tx.run(sql`INSERT OR REPLACE INTO search_index (rowid, snapshot_id, url, title, content)
    SELECT rowid, id, url, title, ${tags.join(' ')} FROM core_snapshot WHERE id = ${id}`);

  // Tags keep the order they were added in (core_snapshot_tags.id); only new
  // ones are inserted, so unchanged tags keep their rows.
  const names = [...new Set(tags.filter(Boolean))];
  await tx.delete(core_snapshot_tags).where(and(eq(core_snapshot_tags.snapshot_id, id), notInArray(core_snapshot_tags.tag_id,
    tx.select({ id: core_tag.id }).from(core_tag).where(inArray(core_tag.name, names)))));
  for (const name of names) {
    const [tag] = await tx.insert(core_tag).values({ created_at: now, modified_at: now, name })
      .onConflictDoUpdate({ target: core_tag.name, set: { name } }).returning({ id: core_tag.id });
    await tx.insert(core_snapshot_tags).values({ snapshot_id: id, tag_id: tag!.id }).onConflictDoNothing();
  }

  // One ArchiveResult per capture, as the server records each plugin's run.
  // output_json holds the local capture record; output_files lists its files
  // relative to the plugin folder, like the server's.
  for (const kind of captureKinds) {
    const capture = snapshot[kind];
    if (!capture) {
      await tx.delete(core_archiveresult).where(and(eq(core_archiveresult.snapshot_id, id), eq(core_archiveresult.plugin, capturePlugins[kind])));
      continue;
    }
    const paths = 'parts' in capture && capture.parts?.length ? capture.parts.map(part => part.path) : [capture.path];
    const files = paths.map(path => snapshotRelativePath(snapshot, path)?.split('/').slice(1).join('/') || path);
    const result = {
      modified_at: now, status: 'succeeded', end_ts: capture.capturedAt, output_str: files[0]!, output_json: capture,
      output_files: Object.fromEntries(files.map(file => [file, {}])), output_size: 'size' in capture ? capture.size : 0,
      delete_at: archiveResultDeleteAt(snapshot, kind, config),
    };
    await tx.insert(core_archiveresult).values({ id: uuidv7(), created_at: now, snapshot_id: id, plugin: capturePlugins[kind], ...result })
      .onConflictDoUpdate({ target: [core_archiveresult.snapshot_id, core_archiveresult.plugin, core_archiveresult.hook_name], set: result });
  }

  const copies = Object.entries(snapshot.remote_copies || {});
  await tx.delete(remote_copies).where(and(eq(remote_copies.snapshot_id, id), notInArray(remote_copies.server_id, copies.map(([server]) => server))));
  for (const [server_id, remote_copy] of copies) {
    await tx.insert(remote_copies).values({ snapshot_id: id, server_id, remote_copy })
      .onConflictDoUpdate({ target: [remote_copies.snapshot_id, remote_copies.server_id], set: { remote_copy } });
  }
}

type SnapshotRow = typeof core_snapshot.$inferSelect;

// Reassembles rows into the Snapshot shape callers use.
async function readSnapshots(tx: Tx, rows: SnapshotRow[]): Promise<Snapshot[]> {
  if (!rows.length) return [];
  const ids = rows.map(row => row.id);
  const tags = await tx.select({ snapshot_id: core_snapshot_tags.snapshot_id, name: core_tag.name }).from(core_snapshot_tags)
    .innerJoin(core_tag, eq(core_tag.id, core_snapshot_tags.tag_id))
    .where(inArray(core_snapshot_tags.snapshot_id, ids)).orderBy(core_snapshot_tags.id);
  const results = await tx.select({ snapshot_id: core_archiveresult.snapshot_id, plugin: core_archiveresult.plugin, output_json: core_archiveresult.output_json })
    .from(core_archiveresult).where(inArray(core_archiveresult.snapshot_id, ids));
  const copies = await tx.select().from(remote_copies).where(inArray(remote_copies.snapshot_id, ids));
  return rows.map(row => {
    const snapshot: Snapshot = {
      id: row.id, url: row.url, timestamp: row.bookmarked_at, created_by_username: row.created_by_username,
      title: row.title, depth: row.depth as Snapshot['depth'],
      tags: tags.filter(tag => tag.snapshot_id === row.id).map(tag => tag.name),
    };
    if (row.favIconUrl !== null) snapshot.favIconUrl = row.favIconUrl;
    if (row.persona_overrides !== null) snapshot.persona_overrides = row.persona_overrides;
    if (row.unassigned_remote_copy !== null) snapshot.unassigned_remote_copy = row.unassigned_remote_copy as RemoteCopy;
    for (const result of results) {
      const kind = captureKinds.find(kind => capturePlugins[kind] === result.plugin);
      if (kind && result.snapshot_id === row.id) Object.assign(snapshot, { [kind]: result.output_json });
    }
    for (const copy of copies) {
      if (copy.snapshot_id === row.id) snapshot.remote_copies = { ...snapshot.remote_copies, [copy.server_id]: copy.remote_copy as RemoteCopy };
    }
    return snapshot;
  });
}

async function selectSnapshots(tx: Tx, where: SQL | undefined, options: { orderBy?: SQL[]; limit?: number; offset?: number } = {}): Promise<Snapshot[]> {
  let query = tx.select().from(core_snapshot).where(where).orderBy(...(options.orderBy ?? [])).$dynamic();
  if (options.limit !== undefined) {
    // Sort only rowids, then fetch the bounded page's full records. Broad FTS
    // matches otherwise copy every snapshot's fields into the temporary sort.
    const rowid = sql<number>`"core_snapshot".rowid`;
    const page = tx.select({ rowid }).from(core_snapshot).where(where).orderBy(...(options.orderBy ?? []))
      .limit(options.limit).offset(options.offset ?? 0);
    query = query.where(inArray(rowid, page));
  }
  return readSnapshots(tx, await query);
}

// New snapshots belong to the default server's user, like the server's
// created_by, so their captures land in users/{username}/. "system" (the
// server's built-in user) when no server is set up or it is too old to
// report a username.
function withOwner(snapshot: Snapshot, config: ConfigState): Snapshot {
  return { ...snapshot, created_by_username: snapshot.created_by_username || defaultServers(config)[0]?.username || 'system' };
}

// A configured ArchiveBox server's own pages are never saved.
function isServerPage(url: string, config: ConfigState): boolean {
  return config.servers.some(server => server.server && archiveBoxServerUrlMatches(server.server, url));
}

// --- Change notifications ---------------------------------------------------
// Each committed write posts the changed ids to every extension context (popup,
// options page, background). BroadcastChannel skips the sending context, so it
// is notified directly too.

export type SnapshotsChange = { ids: string[] };
const channelName = 'archivebox-snapshots';
const localListeners = new Set<(change: SnapshotsChange) => void>();
let channel: BroadcastChannel | undefined;

function notify(ids: string[]): void {
  channel ??= new BroadcastChannel(channelName);
  channel.postMessage({ ids });
  for (const listener of localListeners) listener({ ids });
}

export function onSnapshotsChanged(listener: (change: SnapshotsChange) => void): () => void {
  const remote = new BroadcastChannel(channelName);
  remote.onmessage = (event: MessageEvent<SnapshotsChange>) => listener(event.data);
  localListeners.add(listener);
  return () => { remote.close(); localListeners.delete(listener); };
}

