// The page's newest snapshot, or a new one from init when the URL has none.
// An existing snapshot only gains a missing title/favicon.
export async function ensureSnapshot(init: Snapshot): Promise<{ snapshot: Snapshot; created: boolean }> {
  const [{ transaction }, config] = await Promise.all([db(), getConfig()]);
  const result = await transaction(async tx => {
    const [existing] = await selectSnapshots(tx, eq(core_snapshot.url, init.url), { orderBy: [desc(core_snapshot.bookmarked_at)], limit: 1 });
    if (existing) {
      if ((existing.title || !init.title) && (existing.favIconUrl || !init.favIconUrl)) return { snapshot: existing, created: false, changed: false };
      const snapshot = { ...existing, title: existing.title || init.title, favIconUrl: existing.favIconUrl || init.favIconUrl || null };
      await writeSnapshot(tx, snapshot, config);
      return { snapshot, created: false, changed: true };
    }
    const snapshot = withOwner(init, config);
    if (isServerPage(init.url, config)) return { snapshot, created: true, changed: false };
    await writeSnapshot(tx, snapshot, config);
    return { snapshot, created: true, changed: true };
  });
  if (result.changed) notify([result.snapshot.id]);
  return { snapshot: result.snapshot, created: result.created };
}

// Saves new snapshots, skipping configured servers' own pages and, with
// skipSavedUrls, any URL that already has a snapshot. Returns those saved.
export async function addSnapshots(snapshots: Snapshot[], options: { skipSavedUrls?: boolean } = {}): Promise<Snapshot[]> {
  const [{ transaction }, config] = await Promise.all([db(), getConfig()]);
  const added: Snapshot[] = [];
  for (let start = 0; start < snapshots.length; start += batchSize) {
    await transaction(async tx => {
      for (const init of snapshots.slice(start, start + batchSize)) {
        if (isServerPage(init.url, config)) continue;
        if (options.skipSavedUrls && (await tx.select({ id: core_snapshot.id }).from(core_snapshot).where(eq(core_snapshot.url, init.url)).limit(1)).length) continue;
        const snapshot = withOwner(init, config);
        await writeSnapshot(tx, snapshot, config);
        added.push(snapshot);
      }
    });
  }
  if (added.length) notify(added.map(snapshot => snapshot.id));
  return added;
}

// Applies fn to each snapshot and saves what changed, in one transaction per
// batch. fn must be synchronous and must not call back into this module: the
// connection is busy until it returns. Returning an unchanged snapshot skips
// the write. Returns the saved snapshots (unchanged ones included).
export async function updateSnapshots(ids: string[], fn: (snapshot: Snapshot) => Snapshot): Promise<Snapshot[]> {
  const [{ transaction }, config] = await Promise.all([db(), getConfig()]);
  const changed: string[] = [];
  const saved: Snapshot[] = [];
  for (let start = 0; start < ids.length; start += batchSize) {
    await transaction(async tx => {
      for (const previous of await selectSnapshots(tx, inArray(core_snapshot.id, ids.slice(start, start + batchSize)))) {
        const updated = fn(structuredClone(previous));
        if (JSON.stringify(updated) === JSON.stringify(previous)) { saved.push(previous); continue; }
        const next = resetChangedCaptureUploads(previous, updated, config);
        await writeSnapshot(tx, next, config);
        changed.push(next.id);
        saved.push(next);
      }
    });
  }
  if (changed.length) notify(changed);
  return saved;
}

export async function updateSnapshot(id: string, fn: (snapshot: Snapshot) => Snapshot): Promise<Snapshot | null> {
  return (await updateSnapshots([id], fn))[0] ?? null;
}

// A recaptured file must be uploaded again: a delivery marked complete goes
// back to accepted for every server whose policy uploads that capture type.
function resetChangedCaptureUploads(previous: Snapshot, snapshot: Snapshot, config: ConfigState): Snapshot {
  if (!snapshot.remote_copies) return snapshot;
  const changed = (kind: CaptureKind) => snapshot[kind] && JSON.stringify(previous[kind]) !== JSON.stringify(snapshot[kind]);
  if (!captureKinds.some(changed)) return snapshot;
  const copies = Object.fromEntries(Object.entries(snapshot.remote_copies).map(([id, copy]) => {
    const policy = { ...defaultServerPolicy, ...config.server_policies[id] };
    const pending = (changed('viewport_screenshot') && policy.upload_viewport_screenshots_to_server)
      || (changed('screenshot') && policy.upload_screenshots_to_server)
      || (changed('mhtml') && policy.upload_mhtml_to_server)
      || (changed('singlefile') && policy.upload_singlefile_to_server);
    return [id, pending ? { ...copy, status: 'accepted' as const } : copy];
  }));
  return { ...snapshot, remote_copies: copies };
}

// Deletes snapshot records (their capture results, tags and receipts with
// them). Capture files are separate: see deleteSnapshotFiles.
export async function deleteSnapshots(ids: string[]): Promise<void> {
  if (!ids.length) return;
  const { transaction } = await db();
  for (let start = 0; start < ids.length; start += batchSize) {
    await transaction(tx => tx.delete(core_snapshot).where(inArray(core_snapshot.id, ids.slice(start, start + batchSize))));
  }
  notify(ids);
}

// Retention settings changed: recompute every delete_at, in batches. Runs
// in the background; until it finishes, retention may act on the old schedule
// for some rows, and always re-checks before deleting.
export async function refreshDeleteAt(): Promise<void> {
  await navigator.locks.request('archivebox-refresh-delete-at', async () => {
    const [{ transaction }, config] = await Promise.all([db(), getConfig()]);
    await walkSnapshots(undefined, async (batch) => {
      await transaction(async tx => {
        for (const snapshot of batch) {
          await tx.update(core_snapshot).set({ delete_at: snapshotDeleteAt(snapshot, config) }).where(eq(core_snapshot.id, snapshot.id));
          for (const kind of captureKinds) {
            if (!snapshot[kind]) continue;
            await tx.update(core_archiveresult).set({ delete_at: archiveResultDeleteAt(snapshot, kind, config) })
              .where(and(eq(core_archiveresult.snapshot_id, snapshot.id), eq(core_archiveresult.plugin, capturePlugins[kind])));
          }
        }
      });
    });
  });
}

// Writes snapshots exactly as given (owner included), replacing any with the
// same id. For restoring data and seeding test fixtures; normal saves go
// through addSnapshots/ensureSnapshot.
export async function putSnapshots(snapshots: Snapshot[]): Promise<void> {
  const [{ transaction }, config] = await Promise.all([db(), getConfig()]);
  for (let start = 0; start < snapshots.length; start += batchSize) {
    await transaction(async tx => {
      for (const snapshot of snapshots.slice(start, start + batchSize)) await writeSnapshot(tx, snapshot, config);
    });
  }
  notify(snapshots.map(snapshot => snapshot.id));
}

