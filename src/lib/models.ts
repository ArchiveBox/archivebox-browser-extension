export async function getSnapshots(ids: string[]): Promise<Snapshot[]> {
  if (!ids.length) return [];
  const { transaction } = await db();
  const found = await transaction(tx => selectSnapshots(tx, inArray(core_snapshot.id, ids)));
  return ids.flatMap(id => found.filter(snapshot => snapshot.id === id));
}

// A URL can have any number of snapshots (captures over time, or as different
// logged-in personas). Callers that show "this page's snapshot" use the newest.
